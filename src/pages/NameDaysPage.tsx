export function NameDaysPage() {
  const today = new Date();
  const [selectedMonth, setSelectedMonth] = useState(today.getMonth() + 1);
  const [selectedDay, setSelectedDay] = useState(today.getDate());
  const [searchName, setSearchName] = useState('');

  const daysCount = daysInMonth(today.getFullYear(), selectedMonth - 1);
  const key = `${selectedMonth}-${selectedDay}`;
  const names = nameDaysData[key] || [];

  // Поиск по имени
  const searchResults: { date: string; month: number; day: number }[] = [];
  if (searchName.length >= 2) {
    const searchLower = searchName.toLowerCase();
    Object.entries(nameDaysData).forEach(([dateKey, namesList]) => {
      if (namesList.some(name => name.toLowerCase().includes(searchLower))) {
        const [m, d] = dateKey.split('-').map(Number);
        searchResults.push({ date: dateKey, month: m, day: d });
      }
    });
  }

  const todayKey = `${today.getMonth() + 1}-${today.getDate()}`;
  const todayNames = nameDaysData[todayKey] || [];

  return (
    <div className="space-y-8">
      <div className="text-center">
        <h1 className="text-3xl md:text-4xl font-bold text-gray-900 mb-2">
          🎂 Календарь именин
        </h1>
        <p className="text-gray-500">Узнайте, когда отмечаются именины</p>
      </div>

      {/* Today's Names */}
      <div className="bg-gradient-to-r from-purple-600 to-pink-600 rounded-2xl p-6 text-white">
        <h2 className="text-xl font-bold mb-3">Именины сегодня — {today.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' })}</h2>
        {todayNames.length > 0 ? (
          <div className="flex flex-wrap gap-2">
            {todayNames.map((name, i) => (
              <span key={i} className="bg-white/20 px-3 py-1 rounded-full text-sm">
                {name}
              </span>
            ))}
          </div>
        ) : (
          <p className="opacity-80">Информация об именинах на сегодня отсутствует</p>
        )}
      </div>

      {/* Search */}
      <div className="bg-white rounded-2xl p-6 shadow-sm border">
        <h3 className="text-lg font-semibold text-gray-900 mb-4">Поиск по имени</h3>
        <input
          type="text"
          value={searchName}
          onChange={(e) => setSearchName(e.target.value)}
          placeholder="Введите имя..."
          className="w-full px-4 py-3 border rounded-lg focus:ring-2 focus:ring-purple-500 focus:border-purple-500"
        />
        
        {searchResults.length > 0 && (
          <div className="mt-4">
            <div className="text-sm text-gray-500 mb-2">
              Найдено дат: {searchResults.length}
            </div>
            <div className="grid grid-cols-2 md:grid-cols-4 lg:grid-cols-6 gap-2">
              {searchResults.slice(0, 24).map(({ month, day }, i) => (
                <button
                  key={i}
                  onClick={() => {
                    setSelectedMonth(month);
                    setSelectedDay(day);
                  }}
                  className="p-2 bg-purple-50 hover:bg-purple-100 rounded-lg text-sm transition"
                >
                  {day} {monthsRu[month - 1].slice(0, 3).toLowerCase()}
                </button>
              ))}
            </div>
          </div>
        )}
      </div>

      {/* Date Selector */}
      <div className="bg-white rounded-2xl p-6 shadow-sm border">
        <h3 className="text-lg font-semibold text-gray-900 mb-4">Выбрать дату</h3>
        <div className="grid md:grid-cols-2 gap-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-2">Месяц</label>
            <select
              value={selectedMonth}
              onChange={(e) => {
                setSelectedMonth(parseInt(e.target.value));
                setSelectedDay(1);
              }}
              className="w-full px-4 py-3 border rounded-lg focus:ring-2 focus:ring-purple-500"
            >
              {monthsRu.map((m, i) => (
                <option key={i} value={i + 1}>{m}</option>
              ))}
            </select>
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-2">День</label>
            <select
              value={selectedDay}
              onChange={(e) => setSelectedDay(parseInt(e.target.value))}
              className="w-full px-4 py-3 border rounded-lg focus:ring-2 focus:ring-purple-500"
            >
              {Array.from({ length: daysCount }, (_, i) => (
                <option key={i + 1} value={i + 1}>{i + 1}</option>
              ))}
            </select>
          </div>
        </div>

        {/* Selected Date Names */}
        <div className="mt-6 p-4 bg-gray-50 rounded-lg">
          <h4 className="font-semibold text-gray-900 mb-3">
            Именины {selectedDay} {monthsRu[selectedMonth - 1].toLowerCase()}
          </h4>
          {names.length > 0 ? (
            <div className="flex flex-wrap gap-2">
              {names.map((name, i) => (
                <span key={i} className="bg-purple-100 text-purple-800 px-3 py-1 rounded-full text-sm font-medium">
                  {name}
                </span>
              ))}
            </div>
          ) : (
            <p className="text-gray-500">Информация об именинах отсутствует</p>
          )}
        </div>
      </div>

      {/* Month Calendar */}
      <div className="bg-white rounded-2xl p-6 shadow-sm border">
        <h3 className="text-lg font-semibold text-gray-900 mb-4">Календарь {monthsRu[selectedMonth - 1]}</h3>
        <div className="grid grid-cols-7 gap-2">
          {['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс'].map(d => (
            <div key={d} className="text-center text-sm text-gray-500 py-2">{d}</div>
          ))}
          
          {/* Calculate first day offset */}
          {(() => {
            const firstDay = new Date(today.getFullYear(), selectedMonth - 1, 1).getDay();
            const offset = firstDay === 0 ? 6 : firstDay - 1;
            const cells = [];
            
            for (let i = 0; i < offset; i++) {
              cells.push(<div key={`empty-${i}`} className="h-12"></div>);
            }
            
            for (let day = 1; day <= daysCount; day++) {
              const dayKey = `${selectedMonth}-${day}`;
              const dayNames = nameDaysData[dayKey] || [];
              const isSelected = day === selectedDay;
              const isToday = day === today.getDate() && selectedMonth === today.getMonth() + 1;
              
              cells.push(
                <button
                  key={day}
                  onClick={() => setSelectedDay(day)}
                  className={`h-12 rounded-lg text-sm transition flex flex-col items-center justify-center ${
                    isSelected ? 'bg-purple-500 text-white' :
                    isToday ? 'bg-purple-100 ring-2 ring-purple-400' :
                    dayNames.length > 0 ? 'bg-gray-50 hover:bg-gray-100' : 'hover:bg-gray-50'
                  }`}
                >
                  <span className="font-medium">{day}</span>
                  {dayNames.length > 0 && !isSelected && (
                    <span className="text-xs text-gray-400">{dayNames.length}</span>
                  )}
                </button>
              );
            }
            
            return cells;
          })()}
        </div>
      </div>

      {/* Info */}
      <div className="bg-purple-50 rounded-2xl p-6">
        <h3 className="text-lg font-semibold text-purple-900 mb-2">Об именинах</h3>
        <div className="text-purple-800 text-sm space-y-2">
          <p>
            <strong>Именины</strong> (День Ангела) — это день памяти святого, в честь которого человек был назван при крещении.
          </p>
          <p>
            В православной традиции именины имеют важное значение и отмечаются наряду с днём рождения.
            В этот день принято поздравлять человека и дарить подарки.
          </p>
          <p>
            Если ваше имя встречается несколько раз в году, вашими именинами считается ближайшая дата после вашего дня рождения.
          </p>
        </div>
      </div>
    </div>
  );
}
